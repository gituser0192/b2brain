const LanguageContext = createContext<Language>("en");

export function LanguageProvider({ language, children }: { language: Language; children: ReactNode }) {
  return <LanguageContext.Provider value={language}>{children}</LanguageContext.Provider>;
}

export function useLanguage() { return useContext(LanguageContext); }

export function translate(language: Language, english: string) {
  return language === "hi" ? hindi[english] ?? english : english;
}

export function LanguageSwitch() {
  const language = useLanguage();
  return <label className="language-switch">{translate(language, "Language")}
    <select aria-label="Language" value={language} onChange={(event) => {
      const next = event.currentTarget.value === "hi" ? "hi" : "en";
      document.cookie = `sathos_lang=${next}; Path=/; Max-Age=31536000; SameSite=Lax${location.protocol === "https:" ? "; Secure" : ""}`;
      location.reload();
    }}>
      <option value="en">English</option><option value="hi">हिन्दी (बीटा)</option>
    </select>
  </label>;
}
